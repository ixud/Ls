#!/usr/bin/env node
/**
 * build-client.mjs — the third lever: inline the renderer into console.html.
 *
 * The widget lives as a normal ES module (`client/renderer.mjs`, covered by
 * tests/run.mjs) but console.html is a single classic-script page, so the module
 * is inlined there — no import/export, wrapped in an IIFE so its local `esc`/`json`
 * never collide with the page's own globals. This tool owns that transform so the
 * two copies cannot drift: run it after editing the renderer.
 *
 *   node tools/build-client.mjs           # rewrite the region in console.html
 *   node tools/build-client.mjs --check   # exit 1 if the page is out of sync
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

export const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const PATHS = path.join(ROOT, 'shared', 'paths.mjs');
const RENDERER = path.join(ROOT, 'client', 'renderer.mjs');
const PAGE = path.resolve(ROOT, '..', 'console.html');
const BEGIN = '/* TUI-SETTINGS-RENDERER:BEGIN — generated by tui-settings/tools/build-client.mjs — do not hand-edit */';
const END = '/* TUI-SETTINGS-RENDERER:END */';

/** Drop import lines and `export ` prefixes so the module becomes plain script code. */
function stripModule(src) {
  return src
    .split(/\r?\n/)
    .filter(l => !/^\s*import\s/.test(l))
    .map(l => l.replace(/^export\s+/, ''))
    .join('\n');
}

const API = ['createState', 'readPath', 'effectiveValue', 'setDraft', 'clearDraft', 'collectPatches', 'dirtyCount', 'renderSettings', 'normalizeKeyEvent', 'bindSettings'];

export function buildSnippet() {
  const paths = stripModule(fs.readFileSync(PATHS, 'utf8'));
  const renderer = stripModule(fs.readFileSync(RENDERER, 'utf8'));
  const ret = 'return { ' + API.join(', ') + ' };';
  return `${BEGIN}\nconst TUIWidget = (() => {\n${paths}\n\n${renderer}\n\n${ret}\n})();\n${END}`;
}

function splice(page, snippet) {
  const b = page.indexOf(BEGIN);
  const e = page.indexOf(END);
  if (b < 0 || e < 0 || e < b) throw new Error('markers not found in console.html — expected ' + BEGIN.slice(0, 40) + ' … ' + END);
  return page.slice(0, b) + snippet + page.slice(e + END.length);
}

const checkOnly = process.argv.includes('--check');
const snippet = buildSnippet();
const page = fs.readFileSync(PAGE, 'utf8');
const next = splice(page, snippet);

if (checkOnly) {
  const same = page === next;
  console.log(same ? 'OK console.html tui renderer in sync' : 'RENDERER DRIFT — run: node tui-settings/tools/build-client.mjs');
  process.exit(same ? 0 : 1);
}
fs.writeFileSync(PAGE, next, 'utf8');
console.log('inlined tui renderer into console.html (' + snippet.length + ' chars)');
