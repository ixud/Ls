#!/usr/bin/env node
/**
 * gen-model.mjs — the second lever: the tui keybind allowlist.
 *
 * cliToTui() renames cli keybind IDs to their legacy tui.json names using the
 * map extracted from the opencode binary. That map is bigger than the legacy
 * schema: 22 of its tui names (`open_menu`, `session_tab_next`, …) are NOT in
 * `tui.schema.json`, so writing them produces keys the TUI never reads. The
 * fix is to write only names the legacy schema knows — and the honest way to
 * get that list is to read `tui.schema.json` itself, not to hand-copy it.
 *
 * Output: schema/tui-keybind-names.json — the array of keybind names valid per
 * `tui.schema.json`, plus the provenance needed to re-derive it.
 *
 * `tui.schema.json` is 1.15 MB and is not committed; pass it in:
 *   node tools/gen-model.mjs --tui-schema=<path-to-tui.schema.json>
 * or drop it at schema/tui.schema.json and run with no arguments.
 *
 *   node tools/gen-model.mjs --check     # exit 1 if the allowlist would change
 */
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { fileURLToPath } from 'node:url';

export const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
export const SCHEMA_DIR = path.join(ROOT, 'schema');

const argv = process.argv.slice(2);
const opt = name => { const hit = argv.find(a => a.startsWith('--' + name + '=')); return hit ? hit.slice(name.length + 3) : null; };
const checkOnly = argv.includes('--check');

/** Where the raw tui schema may sit, in priority order. */
function findTuiSchema() {
  const explicit = opt('tui-schema');
  const candidates = [
    explicit,
    path.join(SCHEMA_DIR, 'tui.schema.json'),
    path.resolve(ROOT, '..', 'schema', 'tui.schema.json'),
  ].filter(Boolean);
  for (const p of candidates) if (fs.existsSync(p)) return p;
  throw new Error('tui.schema.json not found — pass --tui-schema=<path> (the legacy OpenCode TUI schema, ~1.15 MB)');
}

/**
 * The allowlist: names under `properties.keybinds.properties`.
 * @param {object} tuiSchema
 * @returns {string[]} sorted keybind names
 */
export function extractKeybindNames(tuiSchema) {
  const kb = tuiSchema?.properties?.keybinds;
  if (!kb || !kb.properties) throw new Error('tui.schema.json has no properties.keybinds.properties — schema shape changed');
  return Object.keys(kb.properties);
}

function readJson(file) { return JSON.parse(fs.readFileSync(file, 'utf8')); }
function stableText(obj) { return JSON.stringify(obj, null, 2) + '\n'; }

function build(tuiPath) {
  const buf = fs.readFileSync(tuiPath);
  const schema = JSON.parse(buf.toString('utf8'));
  const names = extractKeybindNames(schema).sort();
  return {
    $comment: 'GENERATED by tools/gen-model.mjs from tui.schema.json — keybind names the legacy TUI schema accepts. Anything outside this list must not be mirrored into tui.json.',
    provenance: {
      tuiSchema: { path: tuiPath, bytes: buf.length, sha256_16: crypto.createHash('sha256').update(buf).digest('hex').slice(0, 16) },
    },
    count: names.length,
    names,
  };
}

const tuiPath = findTuiSchema();
const out = build(tuiPath);
const target = path.join(SCHEMA_DIR, 'tui-keybind-names.json');

if (checkOnly) {
  const cur = fs.existsSync(target) ? readJson(target) : null;
  const same = cur && JSON.stringify(cur.names) === JSON.stringify(out.names);
  console.log(same ? 'OK tui keybind allowlist in sync (' + out.count + ' names)' : 'ALLOWLIST DRIFT — regenerate');
  process.exit(same ? 0 : 1);
}

fs.writeFileSync(target, stableText(out), 'utf8');
console.log(`tui schema    : ${tuiPath}`);
console.log(`              ${(out.provenance.tuiSchema.bytes / 1048576).toFixed(2)} MB · sha256:${out.provenance.tuiSchema.sha256_16}`);
console.log(`allowlist     : ${out.count} keybind names -> schema/tui-keybind-names.json`);
