/**
 * Load the committed data files. `tui-keybind-names.json` is the allowlist of
 * keybind names valid per `tui.schema.json` (generated by tools/gen-model.mjs);
 * the 1.15 MB raw schema is NOT loaded at runtime — only this derived list.
 */
export function loadSchemas(dir = SCHEMA_DIR) {
  const read = f => JSON.parse(fs.readFileSync(path.join(dir, f), 'utf8'));
  const tuiAllow = read('tui-keybind-names.json');
  return {
    cli: read('cli.schema.json'),
    keybindDefaults: read('keybind-defaults.json'),
    settingDefaults: read('setting-defaults.json'),
    translate: read('translate-keybinds.json'),
    tuiKeybindNames: tuiAllow.names,
    tuiAllowlist: new Set(tuiAllow.names),
    tuiKeybindNamesMeta: tuiAllow,
  };
}

/* --------------------------------- type reading --------------------------------- */

const isObject = v => v !== null && typeof v === 'object' && !Array.isArray(v);

/** `anyOf: [X, null]` means optional; collapse to a nullable node. */
function unwrapNullable(node) {
  if (!isObject(node) || !Array.isArray(node.anyOf)) return { node, nullable: false };
  const rest = node.anyOf.filter(v => v.type !== 'null');
  if (rest.length === node.anyOf.length) return { node, nullable: false };
  const base = rest.length === 1 ? rest[0] : { anyOf: rest };
  return { node: base, nullable: true };
}

/** Flatten nested `anyOf`s so `anyOf[anyOf[A,B], "turn"]` becomes `[A,B,"turn"]`. */
function flattenVariants(node) {
  if (!isObject(node) || !Array.isArray(node.anyOf)) return [node];
  return node.anyOf.flatMap(flattenVariants);
}

/**
 * Resolve `$ref`s and flatten any `anyOf` they introduce. A `$ref` can point at a
 * node that is itself an `anyOf` (TuiKeybind.BindingValue is), so resolving and
 * flattening have to interleave; a depth guard stops a self-referencing def from
 * looping.
 */
function resolvedVariants(nodeRaw, defs, depth = 0) {
  if (depth > 12) return [];
  const { node } = unwrapNullable(nodeRaw);
  return flattenVariants(node).flatMap(v => {
    const target = v && v.$ref ? defs[v.$ref.replace('#/$defs/', '')] : null;
    if (!target) return [v];
    return resolvedVariants(target, defs, depth + 1);
  }).filter(Boolean);
}

/**
 * The schema's own `description` sometimes states the default in prose
 * ("defaults to 'branch'", "(default: true)"). Those are real defaults with no
 * `default` keyword to read, so parse them rather than hand-copy them.
 */
export function defaultFromDescription(description) {
  const d = String(description || '');
  let m = /defaults? to '([^']+)'/i.exec(d);
  if (m) return m[1];
  m = /\(default:\s*([^)]+)\)/i.exec(d);
  if (m) {
    const v = m[1].trim();
    if (v === 'true') return true;
    if (v === 'false') return false;
    if (/^-?[0-9.]+$/.test(v)) return Number(v);
    return v;
  }
  m = /default is ([^.]+)\./i.exec(d);
  if (m) return m[1].trim();
  return undefined;
}

function labelOf(key) {
  return String(key)
    .replace(/[._]/g, ' ')
    .replace(/([a-z])([A-Z])/g, '$1 $2')
    .replace(/\b\w/g, c => c.toUpperCase());
}

/* ---------------------------------- the walker ---------------------------------- */

/**
 * @param {object} options
 * @param {object} options.cli       cli.schema.json
 * @param {object} options.keybindDefaults  schema/keybind-defaults.json
 * @param {object} options.settingDefaults  schema/setting-defaults.json
 * @param {string} [options.schemaUrl]
 * @returns {{groups: Array, index: Record<string, object>, stats: object}}
 */
export function buildFormModel({ cli, keybindDefaults, settingDefaults, schemaUrl = 'https://opencode.ai/v2/cli.json' }) {
  const defs = cli.$defs || {};
  const runtimeDefaults = { ...settingDefaults.defaults, ...settingDefaults.miniDefaults };
  for (const [id, entry] of Object.entries(keybindDefaults.defaults)) runtimeDefaults['keybinds.' + id] = entry.default;

  const index = {};
  const groups = [];

  const registerTree = field => {
    index[field.path] = field;
    for (const sub of field.subfields || []) registerTree(sub);
  };

  for (const [groupKey, groupNodeRaw] of Object.entries(cli.properties || {})) {
    const { node: groupNode, nullable: groupNullable } = unwrapNullable(groupNodeRaw);

    /* keybinds is one schema object with 242 fields; split it by ID prefix so the
       page is navigable without hand-maintaining a second list. */
    if (groupKey === 'keybinds') {
      const g = buildKeybindGroup({ groupNode, groupNullable, groupNodeRaw, runtimeDefaults, defs, schemaUrl });
      groups.push(g);
      for (const f of g.subgroups.flatMap(s => s.fields)) registerTree(f);
      continue;
    }

    const groupDesc = groupNodeRaw.description || '';
    const isScalar = groupNode.type !== 'object' || !groupNode.properties;
    /* `$schema` is a schema directive, not a setting: it is shown so the group list
       matches the schema exactly, but it is read-only — the GUI never rewrites it. */
    const readOnly = groupKey === '$schema';
    const fields = [];
    if (isScalar) {
      const f = fieldFor({ segments: [groupKey], node: groupNodeRaw, defaults: runtimeDefaults, defs, schemaUrl, group: groupKey });
      if (readOnly) f.readOnly = true;
      fields.push(f);
    } else {
      for (const [key, node] of Object.entries(groupNode.properties)) {
        fields.push(fieldFor({ segments: [groupKey, key], node, defaults: runtimeDefaults, defs, schemaUrl, group: groupKey }));
      }
    }
    for (const f of fields) registerTree(f);

    const label = GROUP_LABELS[groupKey] || { th: groupKey, en: labelOf(groupKey) };
    groups.push({
      id: groupKey,
      kind: isScalar ? 'scalar' : 'object',
      label: label.th,
      labelEn: label.en,
      description: groupDesc,
      nullable: groupNullable,
      additionalProperties: groupNode.additionalProperties,
      fields,
    });
  }

  const order = [...GROUP_ORDER.filter(g => groups.some(x => x.id === g)), ...groups.map(g => g.id).filter(g => !GROUP_ORDER.includes(g))];
  groups.sort((a, b) => order.indexOf(a.id) - order.indexOf(b.id));

  const allFields = groups.flatMap(g => (g.subgroups ? g.subgroups.flatMap(s => s.fields) : g.fields));
  return {
    schemaUrl,
    groups,
    index,
    stats: {
      schemaPropertyCount: Object.keys(cli.properties || {}).length,
      groupCount: groups.length,
      fieldCount: allFields.length,
      keybindCount: groups.find(g => g.id === 'keybinds')?.fieldCount || 0,
      byType: allFields.reduce((acc, f) => (acc[f.type] = (acc[f.type] || 0) + 1, acc), {}),
      defaultsKnown: allFields.filter(f => f.hasDefault).length,
    },
  };
}

function buildKeybindGroup({ groupNode, groupNullable, groupNodeRaw, runtimeDefaults, defs, schemaUrl }) {
  const byPrefix = new Map();
  for (const [id, node] of Object.entries(groupNode.properties || {})) {
    const prefix = id.includes('.') ? id.split('.')[0] : 'app';
    if (!byPrefix.has(prefix)) byPrefix.set(prefix, []);
    byPrefix.get(prefix).push({ id, node });
  }
  const subgroups = [];
  for (const [prefix, entries] of [...byPrefix.entries()].sort((a, b) => a[0].localeCompare(b[0]))) {
    const fields = entries.map(({ id, node }) =>
      fieldFor({ segments: ['keybinds', id], node, defaults: runtimeDefaults, defs, schemaUrl, group: 'keybinds' }));
    subgroups.push({
      id: `keybinds/${prefix}`,
      label: KEYBIND_SUBGROUP_LABELS[prefix] || prefix,
      labelEn: prefix,
      description: '',
      fields,
    });
  }
  return {
    id: 'keybinds',
    kind: 'keybinds',
    label: GROUP_LABELS.keybinds.th,
    labelEn: 'Keybinds',
    description: groupNodeRaw.description || '',
    nullable: groupNullable,
    bindingShape: describeBindingValue(groupNode.properties?.leader, defs),
    fieldCount: (groupNode.properties && Object.keys(groupNode.properties).length) || 0,
    subgroups,
    fields: [],
  };
}

/**
 * The accepted keybind value shapes, read from $defs so the keybind control can
 * tell the user what is legal without hardcoding it in the client.
 * BindingValue = false | "none" | {name,ctrl,…} | {key,event,preventDefault,fallthrough} | array of those
 */
function describeBindingValue(bindingNodeRaw, defs = {}) {
  if (!bindingNodeRaw) return [];
  const shapes = [];
  for (const v of resolvedVariants(bindingNodeRaw, defs)) {
    if (v.type === 'boolean') shapes.push({ shape: 'disabled', literal: false, note: 'false disables the binding' });
    else if (v.type === 'string' && Array.isArray(v.enum) && v.enum.includes('none')) shapes.push({ shape: 'disabled', literal: 'none', note: '"none" disables the binding' });
    else if (v.type === 'string') shapes.push({ shape: 'key', note: 'comma-separated alternatives, e.g. "ctrl+c,ctrl+d". <leader> is the leader key' });
    else if (v.type === 'object' && v.properties?.name) shapes.push({ shape: 'keyObject', properties: Object.keys(v.properties), required: v.required });
    else if (v.type === 'object' && v.properties?.key) shapes.push({ shape: 'bindingObject', properties: Object.keys(v.properties), required: v.required });
    else if (v.type === 'array') shapes.push({ shape: 'array', note: 'array of keys or binding objects' });
  }
  return shapes;
}

function fieldFor({ segments, node: nodeRaw, defaults, defs, schemaUrl, group }) {
  const { node, nullable: ownNullable } = unwrapNullable(nodeRaw);
  const nullable = ownNullable;
  const desc = node.description || nodeRaw.description || '';
  const key = segments[segments.length - 1];
  const fieldPath = toWire(segments);
  const display = toDisplay(fieldPath);

  const field = {
    path: fieldPath,
    display,
    key,
    group,
    label: labelOf(key),
    description: desc,
    nullable,
    schemaRef: `${schemaUrl}#/${segments.map(s => 'properties/' + s).join('/')}`,
  };

  const resolve = n => (n && n.$ref ? defs[n.$ref.replace('#/$defs/', '')] || null : n);
  const variants = resolvedVariants(nodeRaw, defs);

  /* default resolution: runtime table -> schema description prose -> none */
  if (Object.prototype.hasOwnProperty.call(defaults, display)) {
    field.default = defaults[display];
    field.hasDefault = true;
    field.defaultSource = 'runtime';
  } else {
    const fromDesc = defaultFromDescription(desc);
    if (fromDesc !== undefined) {
      field.default = fromDesc;
      field.hasDefault = true;
      field.defaultSource = 'description';
    } else {
      field.default = null;
      field.hasDefault = false;
      field.defaultSource = 'none';
    }
  }

  const constrain = n => {
    const c = {};
    for (const k of ['minimum', 'maximum', 'exclusiveMinimum', 'exclusiveMaximum', 'minLength', 'maxLength', 'pattern']) {
      if (n[k] !== undefined) c[k] = n[k];
    }
    return Object.keys(c).length ? c : null;
  };

  /* keybind fields carry a reference to BindingValue; name the type after the control, not the JSON */
  const refName = nodeRaw.anyOf?.find(v => v.$ref)?.$ref || node.$ref || '';
  if (/TuiKeybind\.BindingValue/.test(refName)) {
    field.type = 'keybind';
    field.bindingShapes = describeBindingValue(nodeRaw, defs);
    field.nullable = true;
    return field;
  }

  if (variants.length > 1) {
    const types = [...new Set(variants.map(v => v.type))];
    field.type = types.length > 1 ? 'union' : scalarType(types[0], variants[0]);
    field.variants = variants.map(v => ({
      type: scalarType(v.type, v),
      enum: Array.isArray(v.enum) ? v.enum : null,
      description: v.description || '',
    }));
    if (types.length === 1 && types[0] === 'string') {
      field.enum = [...new Set(variants.flatMap(v => (Array.isArray(v.enum) ? v.enum : [])))];
    }
    const c = variants.map(constrain).filter(Boolean);
    if (c.length) field.constraint = Object.assign({}, ...c);
    return field;
  }

  const v = variants[0] || node;
  field.type = scalarType(v.type, v);
  if (Array.isArray(v.enum)) field.enum = v.enum;
  const c = constrain(v);
  if (c) field.constraint = c;

  if (v.type === 'object' && v.properties) {
    field.type = 'object';
    field.subfields = Object.entries(v.properties).map(([k, sub]) =>
      fieldFor({ segments: [...segments, k], node: sub, defaults, defs, schemaUrl, group }));
  } else if (v.type === 'object' && v.additionalProperties) {
    field.type = 'boolmap';
    field.valueType = v.additionalProperties.type || 'any';
  } else if (v.type === 'array') {
    field.type = 'list';
    field.item = { type: v.items?.type || 'union', variants: arrayItemTypes(v.items, resolve) };
  }
  if (Array.isArray(v.required)) field.required = v.required;
  return field;
}

function arrayItemTypes(items, resolve) {
  if (!items) return [];
  const resolved = flattenVariants(items).map(resolve).filter(Boolean);
  return resolved.map(v => ({ type: scalarType(v.type, v), properties: v.properties ? Object.keys(v.properties) : null, required: v.required || null }));
}

function scalarType(type, node) {
  if (Array.isArray(node.enum)) {
    if (node.enum.length === 1 && node.enum[0] === false) return 'boolean';
    return 'enum';
  }
  if (type === 'number') return 'number';
  if (type === 'integer') return 'integer';
  if (type === 'boolean') return 'boolean';
  if (type === 'string') return 'string';
  if (type === 'object') return 'object';
  if (type === 'array') return 'list';
  return 'unknown';
}

/** Undocumented-but-legal enums worth showing: derive from the JSON Schema when present. */
export function fieldPaths(model) {
  const out = [];
  const walk = f => { out.push(f.path); for (const s of f.subfields || []) walk(s); };
  for (const g of model.groups) {
    for (const f of g.fields) walk(f);
    for (const sg of g.subgroups || []) for (const f of sg.fields) walk(f);
  }
  return out;
}
