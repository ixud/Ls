/**
 * form-model.mjs — schema walker.
 *
 * Turns `schema/cli.schema.json` into a UI form model: group -> field ->
 * {type, enum, description, path, default}. Nothing about the CLI's shape is
 * typed into the client; the client renders whatever this emits. Add a key to
 * the schema and it appears in the GUI with no client change.
 *
 * Field `type` values the renderer knows how to draw:
 *   boolean | enum | number | integer | string | keybind | union | object | boolmap | list
 *
 * Defaults come from three sources, in this precedence, each recorded on the
 * field so the UI can label where a default came from:
 *   runtime  — schema/setting-defaults.json / keybind-defaults.json (extracted from the binary)
 *   description — prose inside the schema's own `description` ("defaults to 'branch'")
 *   none     — the program has no default; leaving it out is the default
 */
